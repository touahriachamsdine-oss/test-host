const SPECIAL: Record<string, Record<string, string>> = {
  AP: { en: 'Africa (regional)', fr: 'Afrique (régional)', ar: 'إفريقيا (إقليمي)' },
  Eurasia: { en: 'Eurasia', fr: 'Eurasie', ar: 'أوراسيا' },
  International: { en: 'International', fr: 'International', ar: 'دولي' },
  Unknown: { en: 'Not specified', fr: 'Non précisé', ar: 'غير محدّد' }
};

export function countryLabel(name: string, locale: string): string {
  const special = SPECIAL[name];
  if (special) return special[locale] ?? special.en;
  const code = CODES[name];
  if (!code) return name;
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? name;
  } catch {
    return name;
  }
}
